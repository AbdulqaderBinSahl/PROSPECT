"""Shared utilities for the single-pass baselines (A1 and A2).

Handles: operational config loading, prompt formatting, PDF text extraction
and word-based chunking (delegated to ``rag_corpus_filter.text_extractor`` so
A1/A2 see exactly the text and chunks the multi-agent conditions see), LLM
calls with JSON parsing and retry, and PDF routing to keep/discard folders.
"""

from __future__ import annotations

import json
import logging
import platform
import shutil
import time
from dataclasses import dataclass
from pathlib import Path
from typing import Any, Dict, List, Optional, Type, TypeVar

from pydantic import BaseModel, ValidationError

logger = logging.getLogger(__name__)

T = TypeVar("T", bound=BaseModel)


# ── Operational config ───────────────────────────────────────────────────────


@dataclass
class OperationalConfig:
    application_description: str
    domain_taxonomy: List[str]
    representative_queries: List[str]
    value_criteria: List[Dict[str, Any]]
    anti_patterns: List[str]


def load_operational_config(path: str) -> OperationalConfig:
    """Load the operational config JSON generated by Step 2's config pre-step."""
    with open(path, "r", encoding="utf-8") as f:
        data = json.load(f)
    cfg = OperationalConfig(
        application_description=data["application_description"],
        domain_taxonomy=data.get("domain_taxonomy", []),
        representative_queries=data.get("representative_queries", []),
        value_criteria=data.get("value_criteria", []),
        anti_patterns=data.get("anti_patterns", []),
    )
    logger.info(
        "Loaded operational config: %d queries, %d value criteria, %d anti-patterns",
        len(cfg.representative_queries),
        len(cfg.value_criteria),
        len(cfg.anti_patterns),
    )
    return cfg


def format_criteria_for_prompt(criteria: List[Dict[str, Any]]) -> str:
    """Format value criteria with full 0-5 rubrics into a prompt-ready string."""
    parts = []
    for c in criteria:
        anchors = c.get("scale_anchors", {})
        anchor_lines = "\n".join(
            f"    {score}: {desc}" for score, desc in sorted(anchors.items(), key=lambda x: int(x[0]))
        )
        parts.append(
            f"- **{c['name']}**: {c['description']}\n"
            f"  Scale:\n{anchor_lines}"
        )
    return "\n\n".join(parts)


def format_queries_for_prompt(queries: List[str]) -> str:
    """Format representative queries as a numbered list."""
    return "\n".join(f"  {i}. {q}" for i, q in enumerate(queries, 1))


def format_anti_patterns_for_prompt(patterns: List[str]) -> str:
    """Format anti-patterns as a bulleted list."""
    return "\n".join(f"  - {p}" for p in patterns)


# ── PDF text extraction (matches Step 2) ─────────────────────────────────────


@dataclass
class BaselineLLM:
    """LLM settings for the single-pass baselines."""
    base_url: str
    api_key: str
    model: str
    temperature: float = 0.1
    max_tokens: int = 4096
    max_retries: int = 6

    def info(self) -> Dict[str, Any]:
        """Model and platform details, in the same shape as the A3 family's run_metrics."""
        return {
            "model": self.model, "base_url": self.base_url, "temperature": self.temperature,
            "max_retries": self.max_retries, "platform": platform.platform(),
            "python_version": platform.python_version(),
        }

    def call(self, system_prompt: str, human_prompt: str, response_model: Type[T], context_label: str) -> T:
        """Structured call with these settings (see :func:`call_llm_json`)."""
        return call_llm_json(
            system_prompt=system_prompt,
            human_prompt=human_prompt,
            response_model=response_model,
            endpoint=self.base_url,
            model=self.model,
            api_key=self.api_key,
            temperature=self.temperature,
            max_tokens=self.max_tokens,
            max_retries=self.max_retries,
            context_label=context_label,
        )


def write_manifest(output_dir: Path, condition: str, llm: BaselineLLM, input_info: Dict[str, Any],
                   n_pdfs: int, resume: bool, extra: Optional[Dict[str, Any]] = None) -> Path:
    """Write ``run_manifest.json`` (invocation context) for a baseline run.

    On resume, the first manifest is kept and a session entry is appended.
    """
    import platform
    import sys
    from datetime import datetime

    path = output_dir / "run_manifest.json"
    if resume and path.exists():
        manifest = json.loads(path.read_text(encoding="utf-8"))
        manifest.setdefault("resume_sessions", []).append(
            {"resumed_at": datetime.now().isoformat(), "argv": sys.argv, "n_pdfs_found": n_pdfs}
        )
    else:
        manifest = {
            "run_started_at": datetime.now().isoformat(),
            "condition": condition,
            "inputs": input_info,
            "n_pdfs_found": n_pdfs,
            "llm": {
                "model": llm.model,
                "base_url": llm.base_url,
                "temperature": llm.temperature,
                "max_tokens": llm.max_tokens,
                "max_retries": llm.max_retries,
            },
            **(extra or {}),
            "environment": {
                "platform": platform.platform(),
                "python_version": platform.python_version(),
                "argv": sys.argv,
            },
        }
    path.write_text(json.dumps(manifest, indent=2, ensure_ascii=False), encoding="utf-8")
    return path


def extract_text_from_pdf(pdf_path: Path) -> str:
    """Extract and normalise the full text of a PDF (pages joined by blank lines).

    Uses the same extraction as the multi-agent conditions.
    """
    from rag_corpus_filter.text_extractor import extract_pages

    return "\n\n".join(page.text for page in extract_pages(pdf_path))


# ── LLM client ──────────────────────────────────────────────────────────────


def call_llm_json(
    system_prompt: str,
    human_prompt: str,
    response_model: Type[T],
    endpoint: str,
    model: str,
    api_key: str = "lm-studio",
    temperature: float = 0.1,
    max_tokens: int = 4096,
    max_retries: int = 3,
    context_label: str = "",
) -> T:
    """Call an OpenAI-compatible LLM, parse JSON, validate with Pydantic, retry."""
    from openai import OpenAI

    client = OpenAI(base_url=endpoint, api_key=api_key)

    messages = [
        {"role": "system", "content": system_prompt},
        {"role": "user", "content": human_prompt},
    ]

    last_error: Optional[Exception] = None

    for attempt in range(1, max_retries + 1):
        try:
            response = client.chat.completions.create(
                model=model,
                messages=messages,
                temperature=temperature,
                max_tokens=max_tokens,
            )
            choice = response.choices[0].message
            raw = choice.content or ""
            if not raw.strip():
                # Fallback: check reasoning_content (extended thinking models)
                raw = getattr(choice, "reasoning_content", None) or ""
            logger.debug("[%s] attempt %d raw:\n%s", context_label, attempt, raw[:500])

            parsed = _parse_json_safe(raw)
            if parsed is None:
                logger.warning("[%s] attempt %d: could not parse JSON", context_label, attempt)
                messages.append({"role": "assistant", "content": raw})
                messages.append({"role": "user", "content": (
                    "Your previous response was not valid JSON. "
                    "Please output ONLY the corrected JSON object, nothing else."
                )})
                last_error = ValueError("JSON parse failure")
                continue

            try:
                return response_model.model_validate(parsed)
            except ValidationError as ve:
                logger.warning("[%s] attempt %d: validation failed: %s", context_label, attempt, ve)
                messages.append({"role": "assistant", "content": raw})
                messages.append({"role": "user", "content": (
                    f"Your JSON failed schema validation:\n{ve}\n\n"
                    f"Please output a corrected JSON object matching the required schema."
                )})
                last_error = ve
                continue

        except Exception as exc:
            logger.warning("[%s] LLM call error (attempt %d): %s", context_label, attempt, exc)
            last_error = exc
            if attempt < max_retries:
                time.sleep(2 ** attempt)
            continue

    raise RuntimeError(
        f"[{context_label}] All {max_retries} attempts failed. Last error: {last_error}"
    )


def _parse_json_safe(raw: str) -> Optional[dict]:
    """Try multiple strategies to extract JSON from LLM output."""
    raw = raw.strip()

    # direct parse
    try:
        return json.loads(raw)
    except json.JSONDecodeError:
        pass

    # strip markdown fences
    cleaned = raw
    for marker in ("```json", "```JSON", "```"):
        if cleaned.startswith(marker):
            cleaned = cleaned[len(marker):]
            break
    if cleaned.endswith("```"):
        cleaned = cleaned[:-3]
    cleaned = cleaned.strip()
    try:
        return json.loads(cleaned)
    except json.JSONDecodeError:
        pass

    # find outermost JSON object
    start = raw.find("{")
    if start != -1:
        depth = 0
        in_str = False
        escape = False
        for i in range(start, len(raw)):
            ch = raw[i]
            if escape:
                escape = False
                continue
            if ch == "\\":
                escape = True
                continue
            if ch == '"':
                in_str = not in_str
                continue
            if in_str:
                continue
            if ch == "{":
                depth += 1
            elif ch == "}":
                depth -= 1
                if depth == 0:
                    try:
                        return json.loads(raw[start:i + 1])
                    except json.JSONDecodeError:
                        break

    return None


# ── PDF routing ──────────────────────────────────────────────────────────────


def route_pdf(
    pdf_path: Path,
    decision: str,
    output_dir: Path,
) -> None:
    """Copy a PDF into the appropriate keep/discard subfolder."""
    dest_dir = output_dir / decision
    dest_dir.mkdir(parents=True, exist_ok=True)
    shutil.copy2(str(pdf_path), str(dest_dir / pdf_path.name))
